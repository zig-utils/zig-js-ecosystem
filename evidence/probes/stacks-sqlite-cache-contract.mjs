const { SqliteCacheStore } = await import(process.argv[2]);
let checks = 0;
const check = (value, message) => { if (!value) throw new Error(message); checks++; };
const path = process.argv[3];
const store = new SqliteCacheStore({ path, prefix: 'scope' });
const other = new SqliteCacheStore({ path, prefix: 'SCOPE' });
await store.set('json', { n: 42 });
check((await store.get('json')).n === 42, 'JSON roundtrip');
await store.mset([{ key: 'one', value: 1 }, { key: 'two', value: 2 }]);
check((await store.mget(['one', 'two'])).two === 2, 'multi transaction');
check((await store.keys('*')).length === 3, 'glob keys');
check(await store.getTtl('one') === 0, 'unexpired');
check(await store.ttl('one', 60), 'TTL update');
check(await store.getTtl('one') > Date.now(), 'real epoch TTL');
await store.set('claim', { id: 42 });
const claims = await Promise.all([store.take('claim'), store.take('claim')]);
check(claims.filter(x => x !== undefined).length === 1 && claims[0].id === 42, 'atomic DELETE RETURNING');
check(await store.del('two') === 1 && !(await store.has('two')), 'delete changes');
await other.set('keep', 'other namespace');
await store.flush();
check((await store.keys()).length === 0 && await other.get('keep') === 'other namespace', 'case sensitive namespace flush');
await store.set('persist', { answer: 42 });
await store.close(); await other.close();
const reopened = new SqliteCacheStore({ path, prefix: 'scope' });
check((await reopened.get('persist')).answer === 42, 'file persistence');
const stats = await reopened.getStats(); check(stats.hits === 1 && stats.keys === 1, 'actual statistics');
check((await reopened.fetch('persist', () => { throw new Error('cache hit recomputed'); })).answer === 42, 'persisted cache hit');
await reopened.close();
if (checks !== 12) throw new Error('wrong fixture denominator');
console.log('STACKS SQLITE CACHE 12 CHECKS OK');
